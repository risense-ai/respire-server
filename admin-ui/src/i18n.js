const DICTS = { en: EN, zh: ZH };

function readStored() {
  try {
    const v = localStorage.getItem(STORAGE);
    if (v === 'zh' || v === 'en') return v;
  } catch { /* quota / private mode */ }
  return DEFAULT_LOCALE;
}

let locale = DEFAULT_LOCALE;
const listeners = new Set();

function applyDoc(next) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
  document.documentElement.dataset.locale = next;
}

export function getLocale() {
  return locale;
}

export function t(key, vars) {
  let s = DICTS[locale]?.[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

export function setLocale(next) {
  const loc = next === 'zh' ? 'zh' : 'en';
  locale = loc;
  try { localStorage.setItem(STORAGE, loc); } catch { /* ignore */ }
  applyDoc(loc);
  listeners.forEach((fn) => fn(loc));
}

export function bootLocale() {
  locale = readStored();
  applyDoc(locale);
}

export function subscribeLocale(fn) {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

export function missingLocaleKeys() {
  const zh = new Set(Object.keys(ZH));
  return Object.keys(EN).filter((k) => !zh.has(k));
}

bootLocale();
